const fs=require('fs'),path=require('path')
const root=fs.readFileSync('_dev/artifacts/project_completion_release_root.txt','utf8').trim()
const local=fs.readFileSync('worker/motion_automation_worker.py','utf8').replaceAll('\r\n','\n')
const file=path.join(root,'worker/motion_automation_worker.py')
let source=fs.readFileSync(file,'utf8').replaceAll('\r\n','\n')
const a=local.indexOf('def recover_supplemental('),b=local.indexOf('def publish_supplemental(',a)
if(a<0||b<0||source.includes('def recover_supplemental('))throw Error('Unexpected recovery source')
source=source.replace('def publish_supplemental(',local.slice(a,b)+'def publish_supplemental(')
source=source.replace("timing_sha256=package['timing_sha256'],review=", "timing_sha256=package['timing_sha256'],width=package['width'],height=package['height'],review=")
