const fs = require('fs'), path = require('path')
const root = fs.readFileSync('_dev/artifacts/project_completion_release_root.txt', 'utf8').trim()
const web = path.join(root, 'auth-web')
const route = path.join(web, 'app/api/std/projects/route.ts')
let source = fs.readFileSync(route, 'utf8')
source = "import { attachStdProjectCategories } from '@/lib/stdProjectCategories'\n" + source
