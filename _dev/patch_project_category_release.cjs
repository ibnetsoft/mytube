const page = path.join(web, 'app/std/page.tsx')
source = fs.readFileSync(page, 'utf8')
const a = source.indexOf('                                            const projectCatName = (() => {')
const b = source.indexOf('                                            const projectThumbnailUrl', a)
if (a < 0 || b < 0) throw Error('Unexpected category display')
source = source.slice(0, a) + "                                            const projectCatName = String(p.category_name || '').trim() || '미분류'\n" + source.slice(b)
fs.writeFileSync(page, source)
for (const file of ['lib/stdProjectCategories.ts', 'tests/std-project-categories.cjs']) fs.copyFileSync(path.join('auth-web', file), path.join(web, file))
const test = path.join(web, 'tests/std-project-cache.cjs')
source = fs.readFileSync(test, 'utf8')
source = source.replace("  '@/lib/stdProjectStatusContext':{loadStdProjectStatusContext:async()=>[context]},", "  '@/lib/stdProjectStatusContext':{loadStdProjectStatusContext:async()=>[context]},\n  '@/lib/stdProjectCategories':load('lib/stdProjectCategories.ts'),")
