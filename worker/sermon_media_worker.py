MEDIA_PROFILE = 'sermon_media/v1'


def file_hash(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def reusable(path, row, identity):
    return (row.get('fingerprint') == identity and Path(path).is_file()
            and row.get('sha256') == file_hash(path))


def command(args, timeout=1800):
    result = subprocess.run([ffmpeg(), '-hide_banner', '-loglevel', 'error', '-y', *map(str, args)],
                            capture_output=True, timeout=timeout)
    if result.returncode:
        # Never surface credentials, URLs, or provider/source data from stderr.
        raise RuntimeError('설교 미디어 변환 실패. 장별 완료 파일은 보존됩니다.')


def wav_duration(path):
    with wave.open(str(path), 'rb') as audio:
        duration = audio.getnframes() / audio.getframerate()
    if duration <= 0:
        raise ValueError('빈 설교 음성입니다.')
    return duration


def video_duration(path):
    result = subprocess.run([ffmpeg(), '-hide_banner', '-i', str(path), '-map', '0:v:0',
                             '-frames:v', '1', '-f', 'null', '-'], capture_output=True, timeout=60)
    text = result.stderr.decode('utf-8', errors='replace')
    match = re.search(r'Duration:\s*(\d+):(\d+):(\d+(?:\.\d+)?)', text)
    if result.returncode or not match or not re.search(r'frame=\s*[1-9]', text):
        raise ValueError('설교 영상이 정상적으로 열리지 않습니다.')
    hours, minutes, seconds = map(float, match.groups())
    return hours * 3600 + minutes * 60 + seconds


def concatenate(paths, target):
    # Paths are generated by this worker. Use relative filenames so FFmpeg safe mode stays enabled.
    listing = target.with_suffix('.concat.txt')
    import shutil
    files = []
    for i, path in enumerate(paths):
        # Generated basename is independent of user titles and external paths.
        link = target.parent / f'{target.stem}-input-{i:04d}.mp4'
        if link.exists():
            link.unlink()
        try:
            os.link(path, link)
        except OSError:
            shutil.copyfile(path, link)
        files.append(link)
    listing.write_text(''.join(f"file '{p.name}'\n" for p in files), encoding='utf-8')
    try:
        command(['-f', 'concat', '-safe', '1', '-i', listing, '-c', 'copy', '-movflags', '+faststart', target], 3600)
    finally:
        for path in files:
            path.unlink(missing_ok=True)


def elevenlabs_keys():
    from worker.script_worker_store import ScriptStore
    keys = ''
    if os.getenv('SUPABASE_SERVICE_ROLE_KEY'):
        rows, _ = ScriptStore().request('GET', 'global_settings', params={'select': 'key,value',
            'key': 'in.(sys_api_elevenlabs,sys_api_elevenlabs_keys)'})
        keys = ' '.join(str(row.get('value') or '') for row in rows)
    if not keys.strip():
        keys = (os.getenv('ELEVENLABS_API_KEY', '') + ' ' + os.getenv('ELEVENLABS_API_KEYS', ''))
    result = []
    for key in re.split(r'[\s,;]+', keys):
        if key and key not in result and not re.fullmatch(r'[•*]+', key) and key.lower() not in ('null', 'undefined', '(unset)', '(미설정)'):
            result.append(key)
    return result[:4]


def synthesize(text, target, config, previous='', following=''):
    keys = elevenlabs_keys()
    if not keys:
        raise ValueError('ElevenLabs API 키를 설정하세요. 완료한 음성은 보존됩니다.')
    voice = config['voice_id']
    if not re.fullmatch(r'[A-Za-z0-9_-]{1,100}', voice):
        raise ValueError('올바른 설교 음성 ID가 필요합니다.')
    for key in keys:
        for attempt in range(3):
            response = requests.post('https://api.elevenlabs.io/v1/text-to-speech/' + voice,
                params={'output_format': 'mp3_44100_128'}, headers={'xi-api-key': key},
                json={'text': text, 'model_id': 'eleven_multilingual_v2', 'language_code': config['language'],
                      'previous_text': previous[-1000:], 'next_text': following[:1000],
                      'voice_settings': {'stability': .65, 'similarity_boost': .75, 'speed': config['voice_speed']}},
                timeout=180)
            if response.status_code == 429 or response.status_code >= 500:
                if attempt < 2:
                    time.sleep(2 ** attempt)
                    continue
            if response.status_code in (401, 402, 403, 429):
                break
            if not response.ok or not response.content or 'audio' not in response.headers.get('Content-Type', ''):
                raise RuntimeError('설교 음성 생성 실패. 음성 ID·잔여 사용량·연결을 확인하세요.')
            nonce = uuid.uuid4().hex
            mp3 = target.with_suffix('.' + nonce + '.download.mp3')
            decoded = target.with_suffix('.' + nonce + '.wav')
            mp3.write_bytes(response.content)
            try:
                command(['-i', mp3, '-ar', '48000', '-ac', '1', '-c:a', 'pcm_s16le', decoded])
                wav_duration(decoded)
                decoded.replace(target)
            finally:
                mp3.unlink(missing_ok=True)
                decoded.unlink(missing_ok=True)
            return
    raise RuntimeError('설교 음성 키 사용량 또는 접근 오류. 완료 음성은 보존됩니다.')


def font_path(language='ko'):
    choices = [os.getenv('SERMON_FONT_PATH', ''), '/System/Library/Fonts/AppleSDGothicNeo.ttc',
               '/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc']
    if language in ('en', 'es'):
        choices.append('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf')
    for path in choices:
        if path and Path(path).is_file():
            return path
    raise ValueError('설교 화면 글꼴을 SERMON_FONT_PATH로 설정하세요.')


def slide(title, text, citations, target, number, total, font=None):
    from PIL import Image, ImageDraw, ImageFont
    image = Image.new('RGB', (1920, 1080), '#101c2c')
    draw = ImageDraw.Draw(image)
    font = font or font_path()
    header = ImageFont.truetype(font, 44)
    small = ImageFont.truetype(font, 28)
    draw.rectangle((110, 165, 1810, 171), fill='#c9b17d')
    # Fit prose into the available area, never clip Scripture at an arbitrary character boundary.
    def wrap(value, face, width):
        lines, current = [], ''
        for char in value:
            if char == '\n' or draw.textlength(current + char, font=face) > width:
                lines.append(current)
                current = '' if char == '\n' else char
            else:
                current += char
        return lines + ([current] if current else [])
    header_lines = wrap(title, header, 1680)
    if len(header_lines) > 2:
        raise ValueError('설교 장 제목이 화면에 들어가지 않습니다. 제목을 줄여 주세요.')
    draw.multiline_text((120, 40), '\n'.join(header_lines), font=header, fill='#e7d2a5', spacing=4)
    for size in (54, 48, 42, 36, 30):
        body = ImageFont.truetype(font, size)
        lines = wrap(text, body, 1640)
        if len(lines) * (size + 16) <= 690:
            break
    else:
        raise ValueError('설교 화면 본문이 너무 깁니다. 장면 대본을 나누세요.')
    draw.multiline_text((140, 190), '\n'.join(lines), font=body, fill='#f1f3f5', spacing=16)
    refs = ' · '.join(dict.fromkeys((c.get('translation', '') + ' ' + c['locator']).strip() for c in citations))
    footer = wrap(refs, small, 1480)
    if len(footer) > 3:
        raise ValueError('설교 화면 인용 위치가 너무 깁니다. 장면 출처를 나누세요.')
    draw.multiline_text((140, 920), '\n'.join(footer), font=small, fill='#c1ccda', spacing=4)
    draw.text((1690, 1000), f'{number} / {total}', font=small, fill='#c1ccda')
    image.save(target)


def process_sermon(candidate, directory, config, notify=lambda value: None, should_stop=lambda: False, audio_fn=synthesize):
    plan = candidate.get('sermon_plan', {})
    if plan.get('profile') != PROFILE or not plan.get('chapters'):
        raise ValueError('검토 완료된 장별 설교 계획이 필요합니다.')
    chapters = plan['chapters']
    validate_continuity(plan['final_review'], chapters)
    for chapter in chapters:
        if chapter.get('status') != 'reviewed':
            raise ValueError('설교 장별 검토를 먼저 완료하세요.')
        package = chapter['package']
        if chapter.get('package_hash') != fingerprint(package):
            raise ValueError('설교 장별 검토본의 파일 지문이 다릅니다.')
        validate_citations(package, package['source_manifest'])
        validate_grounding_review(package['grounding_report'], package['sections'])
        if package['script'] != '\n\n'.join(s['text'] for s in package['sections']):
            raise ValueError('설교 대본과 검토한 장면 본문이 다릅니다.')
    if candidate['script'] != '\n\n'.join(c['package']['script'] for c in chapters):
        raise ValueError('설교 전체 대본이 장별 검토본과 다릅니다.')
    root = Path(directory)
    root.mkdir(parents=True, exist_ok=True)
    manifest_path = root / 'media.json'
    identity = fingerprint({'profile': MEDIA_PROFILE, 'plan': plan, 'config': config})
    state = json.loads(manifest_path.read_text(encoding='utf-8')) if manifest_path.exists() else {}
    if state and state.get('fingerprint') != identity:
        raise ValueError('설교 대본·음성 설정이 달라졌습니다. 새 제작 작업을 시작하세요.')
    state = state or {'profile': MEDIA_PROFILE, 'fingerprint': identity, 'audio': {}, 'video': {}, 'chapters': {}}
    state.pop('error', None)
    flattened = [(c, s) for c in chapters for s in c['package']['sections']]
    last_progress = None
    def report(status, **extra):
        nonlocal last_progress
        state.update(status=status, **extra)
        save(manifest_path, state)
        progress = {k: state[k] for k in ('status', 'current_chapter', 'completed_chapters', 'duration_seconds', 'error') if k in state}
        if progress != last_progress:
            notify(progress)
            last_progress = progress
    try:
        total_audio = 0
        for index, (chapter, section) in enumerate(flattened):
            if should_stop():
                report('interrupted')
                return state
            key = f"ch{chapter['chapter_number']:03d}-s{section['scene_order']:04d}"
            audio = root / (key + '.wav')
            previous = flattened[index-1][1]['text'] if index else ''
            following = flattened[index+1][1]['text'] if index+1 < len(flattened) else ''
            scope = fingerprint({'text': section['text'], 'config': config, 'previous': previous[-1000:], 'next': following[:1000]})
            entry = state['audio'].get(key, {})
            report('audio', current_chapter=chapter['chapter_number'])
            if not reusable(audio, entry, scope):
                audio_fn(section['text'], audio, config, previous, following)
                entry = {'fingerprint': scope, 'sha256': file_hash(audio), 'duration_seconds': wav_duration(audio)}
                state['audio'][key] = entry
                save(manifest_path, state)
            total_audio += wav_duration(audio)
        target = float(plan['target_duration_seconds'])
        tempo = min(1., total_audio / (target + len(flattened) * .08))
        if tempo < .85:
            raise ValueError('실제 음성이 목표보다 15% 이상 짧습니다. 대본 분량 보완이 필요합니다. 음성은 보존됩니다.')
        state['narration_duration_seconds'] = total_audio
        state['playback_tempo'] = tempo
        chapter_outputs, total_duration = [], 0
        for chapter in chapters:
            clips = []
            report('video', current_chapter=chapter['chapter_number'])
            for section in chapter['package']['sections']:
                if should_stop():
                    report('interrupted')
                    return state
                key = f"ch{chapter['chapter_number']:03d}-s{section['scene_order']:04d}"
                audio, image, video = [root / (key + suffix) for suffix in ('.wav', '.png', '.mp4')]
                duration = state['audio'][key]['duration_seconds'] / tempo
                scope = fingerprint({'audio': state['audio'][key], 'tempo': tempo, 'section': section,
                                     'title': chapter['title'], 'font': file_hash(config['font_path']), 'profile': MEDIA_PROFILE})
                if not reusable(video, state['video'].get(key, {}), scope):
                    slide(chapter['title'], section['text'], section['citations'], image,
                          chapter['chapter_number'], len(chapters), config['font_path'])
                    temporary = video.with_suffix('.' + uuid.uuid4().hex + '.render.mp4')
                    command(['-loop', '1', '-framerate', '24', '-i', image, '-i', audio,
                             '-af', f'atempo={tempo:.8f}', '-t', f'{duration:.6f}', '-c:v', 'libx264',
                             '-preset', 'ultrafast', '-tune', 'stillimage', '-pix_fmt', 'yuv420p',
                             '-c:a', 'aac', '-ar', '48000', '-ac', '2', '-b:a', '192k', temporary])
                    actual = video_duration(temporary)
                    if abs(actual - duration) > .5:
                        raise ValueError('장면 영상 길이가 실제 음성과 다릅니다.')
                    temporary.replace(video)
                    state['video'][key] = {'fingerprint': scope, 'sha256': file_hash(video), 'duration_seconds': actual}
                    save(manifest_path, state)
                clips.append(video)
            number = str(chapter['chapter_number'])
            output = root / f"chapter-{chapter['chapter_number']:03d}.mp4"
            scope = fingerprint([state['video'][f"ch{chapter['chapter_number']:03d}-s{s['scene_order']:04d}"]
                                 for s in chapter['package']['sections']])
            if not reusable(output, state['chapters'].get(number, {}), scope):
                temporary = output.with_suffix('.' + uuid.uuid4().hex + '.join.mp4')
                concatenate(clips, temporary)
                duration = video_duration(temporary)
                temporary.replace(output)
                state['chapters'][number] = {'fingerprint': scope, 'sha256': file_hash(output), 'duration_seconds': duration}
                save(manifest_path, state)
            total_duration += state['chapters'][number]['duration_seconds']
            chapter_outputs.append(output)
            report('video', completed_chapters=len(chapter_outputs))
        report('assembling')
        final = root / 'sermon-final.mp4'
        scope = fingerprint(state['chapters'])
        if not reusable(final, state.get('final', {}), scope):
            temporary = root / ('sermon-final.' + uuid.uuid4().hex + '.join.mp4')
            concatenate(chapter_outputs, temporary)
            duration = video_duration(temporary)
            if duration + .1 < target or abs(duration - total_duration) > max(2, len(chapters) * .5):
                raise ValueError('최종 설교 영상 재생시간이 목표·장별 영상 합계와 다릅니다.')
            temporary.replace(final)
            state['final'] = {'fingerprint': scope, 'sha256': file_hash(final), 'duration_seconds': duration}
        offsets, elapsed = [], 0
        for c in chapters:
            duration = state['chapters'][str(c['chapter_number'])]['duration_seconds']
            offsets.append({'chapter_number': c['chapter_number'], 'title': c['title'],
                            'start_seconds': elapsed, 'duration_seconds': duration})
            elapsed += duration
        state['timeline'] = offsets
        state['output'] = str(final.resolve())
        report('review_pending', duration_seconds=state['final']['duration_seconds'], error='')
        return state
    except Exception as exc:
        report('failed', error=str(exc) if isinstance(exc, ValueError) else '설교 제작 중단. 완료 파일을 보존했습니다. 설정·연결 확인 후 이어서 제작하세요.')
        raise
