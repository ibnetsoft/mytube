const assert = require('node:assert/strict')
const fs = require('node:fs'), ts = require('typescript')
const api = {}
new Function('exports', ts.transpile(fs.readFileSync(require.resolve('../lib/stdAudioMix.ts'), 'utf8'), {module:ts.ModuleKind.CommonJS}))(api)
const rows = [{scene_number:2,start_num:6.9,end_num:10},{scene_number:2,start_num:10,end_num:19.2},{scene_number:3,start_num:19.2,end_num:25.6}]
const range = api.backgroundWindow({bgm_start_scene:2,bgm_end_scene:3,bgm_fade_in:2,bgm_fade_out:2}, rows, 100)
assert.equal(range.start,6.9); assert.equal(range.end,25.6)
for (const [t,g] of [[0,0],[6.9,0],[7.9,.5],[15,1],[24.6,.5],[25.6,0],[99,0]]) assert.ok(Math.abs(api.backgroundEnvelope(t,range)-g)<1e-9)
assert.equal(api.backgroundWindow({bgm_start_scene:4},rows,100).valid,false)
assert.equal(api.backgroundWindow({bgm_start_scene:3,bgm_end_scene:2},rows,100).valid,false)
assert.equal(api.backgroundWindow({},rows,100).end,100)
const short = api.backgroundWindow({bgm_start_scene:3,bgm_end_scene:3,bgm_fade_in:30,bgm_fade_out:30},rows,100)
assert.ok(Math.abs(short.fadeIn-3.2)<1e-9)
console.log('PASS: recorded scene range, fade envelope, invalid selections, short ranges and full timeline')
const route = fs.readFileSync(require.resolve('../app/api/std/projects/[projectId]/route.ts'),'utf8')
const begin = route.indexOf("    if (projectPayloadPatch.render_settings && ['audio', 'subtitle'].includes(body.render_settings_scope))")
const end = route.indexOf('    if (projectPayloadPatch.render_settings?.comic',begin)
const save = new Function('projectPayloadPatch','body','project',ts.transpile(route.slice(begin,end)+'\nreturn projectPayloadPatch.render_settings', {module:ts.ModuleKind.CommonJS}))
const settings = {bgm_start_scene:2,bgm_end_scene:3,bgm_fade_in:2,bgm_fade_out:3,bgm_asset_id:'music'}
const saved = save({render_settings:settings},{render_settings_scope:'audio'},{project_payload:{render_settings:{subtitle_font_family:'Malgun Gothic'}}})
assert.deepEqual(saved,{subtitle_font_family:'Malgun Gothic',...settings})
const kept = save({render_settings:{bgm_start_scene:0,subtitle_font_family:'Other'}},{render_settings_scope:'subtitle'},{project_payload:{render_settings:settings}})
assert.equal(kept.bgm_start_scene,2)
console.log('PASS: audio save persists range and fades; subtitle save preserves BGM range')

const selected = api.backgroundWindow({bgm_start_scene:100,bgm_end_scene:101,bgm_fade_in:4,bgm_fade_out:4},
    [{scene_number:100,start_num:793.8,end_num:823.7},{scene_number:101,start_num:823.7,end_num:827.1}],827.1)
const once = api.backgroundPlaybackWindow(selected,30,false)
assert.equal(once.end,823.8)
for (const [time,gain] of [[819.8,1],[821.8,.5],[823.3,.125],[823.8,0],[827,0]]) {
    assert.ok(Math.abs(api.backgroundEnvelope(time,once)-gain)<1e-9, `one-shot gain at ${time}`)
}
assert.equal(selected.end,827.1,'playback must not change the saved scene range')
assert.deepEqual(api.backgroundPlaybackWindow(selected,30,true),selected,'looping track uses scene end')
assert.deepEqual(api.backgroundPlaybackWindow(selected,60,false),selected,'longer track uses scene end')
for (const unknown of [0,NaN,Infinity]) assert.deepEqual(api.backgroundPlaybackWindow(selected,unknown,false),selected)
const tiny = api.backgroundPlaybackWindow(selected,2,false)
assert.equal(tiny.fadeIn,1); assert.equal(tiny.fadeOut,1)
const noFade = api.backgroundPlaybackWindow({...selected,fadeIn:0,fadeOut:0},30,false)
assert.equal(api.backgroundEnvelope(823.79,noFade),1)
assert.equal(api.backgroundEnvelope(823.8,noFade),0)
console.log('PASS: one-shot fades at source end; loops, longer tracks, unknown metadata, short tracks and zero fades')

const cueSettings = {bgm_start_scene:2,bgm_start_subtitle:2,bgm_end_scene:3,bgm_fade_in:0,bgm_fade_out:0}
const cue = api.backgroundWindow(cueSettings,rows,100)
assert.equal(cue.start,10,'second subtitle is numbered within the start scene')
assert.equal(cue.end,25.6,'music continues through the next scene')
assert.equal(api.backgroundEnvelope(9.9,cue),0)
assert.equal(api.backgroundEnvelope(10,cue),1)
assert.equal(api.backgroundEnvelope(20,cue),1,'scene transition must not end background playback')
assert.equal(api.backgroundWindow({...cueSettings,bgm_end_scene:0},rows,100).end,100)
for (const ordinal of [0,-1,1.5,3,NaN]) assert.equal(api.backgroundWindow({...cueSettings,bgm_start_subtitle:ordinal},rows,100).valid,false)
assert.equal(api.backgroundWindow({...cueSettings,bgm_start_scene:0},rows,100).start,0,'from beginning preserves the full timeline')
const savedCue = save({render_settings:cueSettings},{render_settings_scope:'audio'},{project_payload:{render_settings:{subtitle_font_family:'Malgun Gothic'}}})
assert.equal(savedCue.bgm_start_subtitle,2)
const keptCue = save({render_settings:{bgm_start_subtitle:1}},{render_settings_scope:'subtitle'},{project_payload:{render_settings:savedCue}})
assert.equal(keptCue.bgm_start_subtitle,2,'subtitle saves must not reset music start')
// Execute the actual web render configuration block, not a second implementation.
const queue = fs.readFileSync(require.resolve('../lib/stdRenderQueue.ts'),'utf8')
const configStart = queue.indexOf('                const bgmSubtitles =')
const configEnd = queue.indexOf('\n            })()',configStart)
const renderTiming = new Function('project','projectRenderSettings','subtitles','audioAsset','backgroundWindow',
    ts.transpile(queue.slice(configStart,configEnd),{module:ts.ModuleKind.CommonJS}))
const render = renderTiming({project_payload:{subtitles:rows}},cueSettings,rows.map(r=>({...r,start:r.start_num,end:r.end_num})),{metadata:{duration_seconds:100}},api.backgroundWindow)
assert.deepEqual(render,{bgm_start:10,bgm_end:25.6,bgm_fade_in:0,bgm_fade_out:0})
console.log('PASS: scene-local subtitle cue, next-scene continuation, persistence, invalid cue and web render timing')
