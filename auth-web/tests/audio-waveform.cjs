const assert = require('node:assert/strict')
const fs = require('node:fs')
const ts = require('typescript')
const api = {}
new Function('exports', ts.transpile(fs.readFileSync(require.resolve('../lib/audioWaveform.ts'), 'utf8'), {module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}))(api)
assert.deepEqual(api.audioWaveformPeaks([new Float32Array([0, 0.5, -1, 0])], 2), [0.5, 1])
assert.deepEqual(api.audioWaveformPeaks([new Float32Array([0, 0]), new Float32Array([1, 0.5])], 2), [1, 0.5])
assert.deepEqual(api.audioWaveformPeaks([new Float32Array(5)], 3), [0, 0, 0])
assert.deepEqual(api.audioWaveformPeaks([], 160), [])
assert.deepEqual(api.audioWaveformPeaks([new Float32Array([0.5])], 160), [0.5])
assert.equal(api.backgroundTrackPosition(65, 30), 5)
assert.equal(api.backgroundTrackPosition(30, 30), 0)
assert.equal(api.backgroundTrackPosition(-2, 30), 0)
assert.equal(api.backgroundTrackPosition(10, 0), 0)
console.log('PASS: real sample peaks, both stereo channels, silence, short files and loop position')
