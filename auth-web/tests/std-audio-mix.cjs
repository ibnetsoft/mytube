const result=volume=>build([storageAsset],{bgm_asset_id:'bgm',bgm_volume:volume},{},a=>a?.metadata?.storage_path?{bucket:'content-assets',path:a.metadata.storage_path}:null,()=> 'audio/music.mp3')
