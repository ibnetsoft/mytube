const assert = require('node:assert/strict'), path = require('node:path');
const load = require('./load-ts.cjs');
const h = load(path.resolve('auth-web/lib/stdVoicePerformance.ts'));
const text = '🌙 静かに。ねえ、本当なの？';
const rows = [{scene_number:1,text:'🌙 静かに。'},{scene_number:1,text:'ねえ、本当なの？'}];
const plan = {version:1,source:'codex-ai',model:'eleven_v4',offset_unit:'unicode-codepoint',scenes:[{scene_number:1,source_text:text,cues:[{offset:6,tag:'whispers'}]}]};
const mapped = h.mapVoicePerformance(rows,plan);
assert.equal(mapped[0],undefined);
assert.equal(h.performanceTextForChunk(rows[1].text,rows[1].text,0,mapped[1]),'[whispers] ねえ、本当なの？');
assert.equal(rows[1].text,'ねえ、本当なの？','Display text never contains generated tags');
assert.deepEqual(h.mapVoicePerformance([{...rows[1],text:'edited'}],plan),[undefined]);
const middle = h.normalizeVoicePerformance({version:1,text,cues:[{offset:6,tag:'curious'}]},text);
assert.equal(h.performanceTextForChunk(text,text,0,middle),'🌙 静かに。[curious] ねえ、本当なの？');
assert.throws(()=>h.normalizeVoicePerformance({...middle,text:'old'},text));
assert.throws(()=>h.normalizeVoicePerformance({...middle,cues:[{offset:0,tag:'explosion'}]},text));
const two = [{scene_number:1,text:'조용히 말해요.'},{scene_number:1,text:'계속 속삭여요.'}];
const carry = h.mapVoicePerformance(two,{...plan,scenes:[{scene_number:1,source_text:'조용히 말해요. 계속 속삭여요.',cues:[{offset:0,tag:'whispers'}]}]});
assert.equal(carry[1].cues[0].tag,'whispers','Independent recordings carry the scene delivery');
assert.deepEqual(h.mapVoicePerformance(rows,undefined),[undefined,undefined],'Old scripts have no generated tags');
assert.deepEqual(h.elevenLabsVoiceSettings('eleven_v4',{stability:0.5,similarityBoost:0.75,speed:1.2,style:0.45}),{stability:0.5,similarity_boost:0.75});
assert.equal(h.elevenLabsVoiceSettings('eleven_multilingual_v2',{speed:1.2,style:0.45}).speed,1.2);
console.log('PASS: Unicode/mid-line tags, separate subtitles, stale-plan safety, delivery continuity, v4-only settings');

assert.equal(h.voicePerformanceKey({cues:[{tag:'whispers',offset:0}],text:'hello',version:1}),h.voicePerformanceKey({version:1,text:'hello',cues:[{offset:0,tag:'whispers'}]}),'JSONB field order must preserve stored recording identity');
