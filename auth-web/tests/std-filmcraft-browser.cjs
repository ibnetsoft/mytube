const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),{chromium}=require('@playwright/test')
const {bundle}=require('./std-web-motion-browser.cjs')
const root=path.resolve(__dirname,'..')
async function main(){
 const browser=await chromium.launch({headless:true,channel:'chrome'}),page=await browser.newPage({viewport:{width:1400,height:1000}})
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 try{
  await page.route('http://localhost:43199/**',r=>r.fulfill({contentType:'text/html',body:'<html><body><div id="root"></div></body></html>'}));await page.goto('http://localhost:43199')
  const styles=path.join(root,'.next/static/css');if(fs.existsSync(styles))for(const file of fs.readdirSync(styles).filter(n=>n.endsWith('.css')))await page.addStyleTag({path:path.join(styles,file)})
  await page.addScriptTag({path:path.join(root,'node_modules/react/umd/react.development.js')})
  await page.addScriptTag({path:path.join(root,'node_modules/react-dom/umd/react-dom.development.js')})
  await page.addScriptTag({content:bundle(['lib/stdWebMotion.ts','node_modules/ag-psd/index.js','components/StdWebMotionStudio.tsx','components/StdProductionMethodSelector.tsx','lib/stdMotionStudio.ts','components/StdMotionStudio.tsx'].map(p=>path.join(root,p)))})
  await page.evaluate(()=>{
   window.fetch=async()=>({ok:true,json:async()=>({job:null,models:[]})})
   window.saved=[]
   ReactDOM.createRoot(document.getElementById('root')).render(React.createElement(window.Production,{value:{version:1,enabled:false,aspect:'16:9',fps:24,scenes:{}},scenes:[],disabled:false,projectId:'test',headers:{},onSave:async d=>window.saved.push(structuredClone(d)),onUpload:async()=>{}}))
  })
  assert.equal(await page.locator('input[name="production-method"]').count(),4)
  assert.equal(await page.locator('input[value="ae"]').isChecked(),true)
  assert.equal(await page.locator('input[name="final-renderer"][value="python"]').isChecked(),true)
  await page.locator('input[name="final-renderer"][value="filmcraft"]').check()
  assert.equal(await page.evaluate(()=>window.saved.at(-1).final_renderer),'filmcraft')
  assert.equal(await page.locator('input[value="ae"]').isChecked(),true)
  await page.locator('input[value="effectcraft"]').check()
  assert.equal(await page.evaluate(()=>window.saved.at(-1).production_method),'effectcraft')
  await page.locator('input[name="production-method"][value="filmcraft"]').check()
  await page.getByRole('heading',{name:'FilmCraft 자동 제작'}).waitFor()
  const last=await page.evaluate(()=>window.saved.at(-1))
  assert.equal(last.automation.mode,'ae_only');assert.ok(last.alternatives.effectcraft)
  assert.deepEqual(errors,[])
  const output=path.resolve(root,'../output/filmcraft/web-smoke');fs.mkdirSync(output,{recursive:true})
  await page.screenshot({path:path.join(output,'web-selector.png'),fullPage:true})
  await page.locator('input[value="ae"]').check()
  assert.equal(await page.locator('input[value="ae"]').isChecked(),true)
  assert.equal(await page.locator('input[name="final-renderer"][value="filmcraft"]').isChecked(),true)
  await page.locator('input[name="final-renderer"][value="python"]').check()
  assert.equal(await page.evaluate(()=>window.saved.at(-1).final_renderer),'python')
  assert.equal(await page.locator('input[value="ae"]').isChecked(),true)
  console.log('PASS browser: Python final default; FilmCraft opt-in; AE/EffectCraft independent')
 }finally{await browser.close()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
