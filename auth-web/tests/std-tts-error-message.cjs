const assert = require('node:assert/strict')
const fs = require('node:fs')
const ts = require('typescript')
function load(path) { const out = {}; new Function('exports', ts.transpile(fs.readFileSync(path, 'utf8'), {module: 1, target: 7}))(out); return out }
const {formatTtsErrorMessage: format} = load('auth-web/lib/stdTtsErrorMessage.ts')
const {localizeStdActionError: localize} = load('auth-web/lib/stdActionFeedback.ts')
const raw = '자막 9번: ElevenLabs TTS API error (401): {"detail":{"code":"subscription_required","message":"Instantly cloned voices are not available on your current plan. Please upgrade your subscription.","status":"ivc_not_permitted","request_id":"private-id"}}'
const result = format(raw)
assert.match(result, /자막 9번.*현재 구독 플랜.*즉시 복제 음성/)
assert.match(result, /다른 음성을 선택/)
assert(!result.includes('private-id'))
for (const locale of ['en', 'th', 'vi']) {
  assert.equal(localize(result, locale, 'tts'), localize(raw, locale, 'tts'))
  assert(!localize(result, locale, 'tts').includes('private-id'))
}
const quota = format('자막 42번: ElevenLabs TTS API error: You have 10 credits remaining, while 21 credits are required')
assert.match(quota, /자막 42번.*잔여 크레딧은 10.*21 크레딧/)
assert(!quota.includes('API error'))
const payment = format('자막 72번: ElevenLabs TTS API error (401): {"detail":{"code":"payment_issue"}}')
assert.match(payment, /구독 결제가 실패/)
assert(!payment.includes('payment_issue'))
assert.match(format('ElevenLabs TTS API error (401): invalid API key'), /API 키와 사용 권한/)
assert(!format('ElevenLabs TTS API error (500): secret').includes('secret'))
assert.match(format('Google quota exceeded (429)'), /Google 음성 API의 요청 한도/)
console.log('PASS: user-friendly TTS guidance')
